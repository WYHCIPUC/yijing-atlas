import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { pathToFileURL } from 'node:url';
const loadModule = name => import(pathToFileURL(path.resolve('web/js/'+name)));
const {buildLearningQuestionBank,LEARNING_LESSONS}=await loadModule('learning-curriculum.js');
const {createAssessmentSession,gradeAssessment}=await loadModule('learning-assessment.js');
const {recordLearningAssessment,loadLearningRecord,getCourseWeakQuestions}=await loadModule('learning-progress.js');
const {exportUserData,parseUserData,importUserData}=await loadModule('user-data.js');
const appState=Object.fromEntries([['hexagrams','hexagrams'],['trigrams','trigrams'],['theorems','theorems'],['wings','wings'],['almanacTerms','almanac-terms']].map(([key,file])=>[key,JSON.parse(fs.readFileSync('web/data/'+file+'.json','utf8'))]));
const bank=buildLearningQuestionBank(appState);
const values=new Map();
const writes=[];
const storage={getItem:key=>values.get(key)??null,setItem:(key,value)=>{values.set(key,value);writes.push(key);},removeItem:key=>values.delete(key)};
const courses=[];
for(const lesson of LEARNING_LESSONS){
  const session=createAssessmentSession('lesson',bank,{lessonId:lesson.id,random:()=>0.25});
  assert.equal(session.questions.length,3);
  const original=session.questions[0];
  const answers=Object.fromEntries(session.questions.map((q,i)=>[q.id,i===0?q.options.find(o=>o.value!==q.answer).value:q.answer]));
  const saved=recordLearningAssessment('lesson',gradeAssessment(session,answers),new Date('2026-10-25T09:00:00Z'),storage);
  assert.equal(saved.saved,true,lesson.id);
  const weak=getCourseWeakQuestions(loadLearningRecord(storage));
  assert.equal(weak.length,1);
  assert.equal(weak[0].questionId,original.id);
  assert.equal(weak[0].targetCode,original.targetCode);
  assert.equal(weak[0].termId,original.termId);
  const retry=createAssessmentSession('lesson',bank,{lessonId:lesson.id,requiredQuestionId:original.id,requiredQuestionVersion:original.questionVersion,random:()=>0.9});
  assert.ok(retry.questions.some(q=>q.id===original.id));
  assert.notEqual(retry.id,session.id);
  const correct=Object.fromEntries(retry.questions.map(q=>[q.id,q.answer]));
  assert.equal(recordLearningAssessment('lesson',gradeAssessment(retry,correct),new Date('2026-10-25T10:00:00Z'),storage).saved,true);
  assert.equal(getCourseWeakQuestions(loadLearningRecord(storage)).length,0);
  const final=loadLearningRecord(storage).weakQuestions[original.id];
  assert.equal(final.status,'resolved'); assert.equal(final.wrongCount,1);
  courses.push({lessonId:lesson.id,type:lesson.type,questionId:original.id,questions:retry.questions.length,status:final.status,targetCode:final.targetCode,termId:final.termId});
}
assert.equal(new Set(writes).size,1);
const exported=exportUserData(storage);
const parsed=parseUserData(JSON.stringify(exported));
const restored=new Map();
const result=importUserData(parsed,{getItem:key=>restored.get(key)??null,setItem:(key,value)=>restored.set(key,value),removeItem:key=>restored.delete(key)});
assert.equal(result, undefined);
assert.deepEqual(JSON.parse(restored.get('yijing-learning-record-v2')),loadLearningRecord(storage));
const report={capturedAt:new Date().toISOString(),kind:'pure integration with real public datasets and synthetic in-memory storage; not browser evidence',questionBank:bank.length,courses:courses.length,roundTrips:courses,wrongThenCorrectSubmissions:50,persistenceKeys:[...new Set(writes)],backupRoundTrip:true,sourceFiles:['learning-curriculum.js','learning-assessment.js','learning-progress.js','user-data.js'].map(name=>({path:'web/js/'+name,sha256:crypto.createHash('sha256').update(fs.readFileSync('web/js/'+name)).digest('hex')}))};
fs.writeFileSync('docs/development/evidence/2026-10-25-course-weak-pipeline.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({questionBank:report.questionBank,courses:report.courses,submissions:50,backupRoundTrip:true,persistenceKeys:report.persistenceKeys}));
