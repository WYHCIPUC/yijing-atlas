const data = JSON.parse(readFileSync(dataPath, 'utf-8'));

let updated = 0;
let missing = [];
for (const hex of data) {
  const note = notes[hex.name];
  if (note) {
    hex.tuanNote = note;
    updated++;
  } else {
    missing.push(hex.name);
  }
}

writeFileSync(dataPath, JSON.stringify(data, null, 2) + '\n', 'utf-8');

console.log(`已更新 ${updated} / ${data.length} 卦`);
