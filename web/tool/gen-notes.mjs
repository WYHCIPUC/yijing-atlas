// ---- 合并写入 ----
const hex = JSON.parse(readFileSync('data/hexagrams.json', 'utf8'));

let missingNames = [];
let lineMiss = 0;
for (const h of hex) {
  const n = notes[h.name];
  if (!n) { missingNames.push(h.name); continue; }
  h.judgementNote = n.judgementNote;
  h.imageNote = n.imageNote;
  h.scenario = n.scenario;
  // 按 position 索引爻注；lines 顺序为初→上 (position 1..6)
  h.lines.forEach((l) => {
    const idx = l.position - 1;
    const ln = n.lines[idx];
    if (!ln) { lineMiss++; return; }
    l.note = ln;
  });
}

if (missingNames.length) {
  console.error('缺少注解的卦：' + missingNames.join(', '));
  process.exit(1);
}
if (lineMiss) {
  console.error('有 ' + lineMiss + ' 条爻辞缺少注解');
  process.exit(1);
}

// 校验注解条数
const expected = hex.length;
let withJudgement = hex.filter(h => h.judgementNote).length;
let withImage = hex.filter(h => h.imageNote).length;
let withScenario = hex.filter(h => h.scenario).length;
let linesWithNote = 0;
hex.forEach(h => h.lines.forEach(l => { if (l.note) linesWithNote++; }));
const expectedLines = expected * 6;

writeFileSync('data/hexagrams.json', JSON.stringify(hex, null, 2) + '\n');

